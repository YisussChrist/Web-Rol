function initialsFromName(name) {
  const clean = (name || '').trim().split(/\s+/).filter(Boolean);
  if (!clean.length) return '?';
  if (clean.length === 1) return clean[0].slice(0, 2).toUpperCase();
  return (clean[0][0] + clean[1][0]).toUpperCase();
}

function makeAvatar(name, cls='avatar') {
  const el = document.createElement('div');
  el.className = cls;
  el.setAttribute('aria-label', name || 'Avatar');
  el.title = name || '';
  el.textContent = initialsFromName(name);
  return el;
}

function makeImageOrAvatar(src, name, cls="avatar") {
  if (!src) return makeAvatar(name, cls);

  const img = document.createElement("img");
  img.className = cls;
  img.src = src;
  img.alt = name || "Imagen";
  img.title = name || "";

  img.onerror = () => {
    img.replaceWith(makeAvatar(name, cls));
  };

  return img;
}
